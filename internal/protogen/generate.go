// Package protogen emits Go bindings for KanaRPC unary and server-streaming RPCs.
package protogen

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

var (
	contextType = protogen.GoIdent{GoImportPath: "context", GoName: "Context"}
	protoType   = protogen.GoIdent{GoImportPath: "google.golang.org/protobuf/proto", GoName: "Message"}
	rpcImport   = protogen.GoImportPath("github.com/KanaDoodle/KanaRPC")
)

func rpc(name string) protogen.GoIdent { return rpcImport.Ident(name) }

// Generate validates every requested service before emitting any files.
func Generate(plugin *protogen.Plugin) error {
	plugin.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL | pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)
	plugin.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_2023
	plugin.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_2024
	for _, file := range plugin.Files {
		if !file.Generate {
			continue
		}
		for _, service := range file.Services {
			for _, method := range service.Methods {
				if method.Desc.IsStreamingClient() {
					return fmt.Errorf("%s: client-streaming and bidirectional RPCs are not supported", method.Desc.FullName())
				}
				if len(methodPath(service, method)) > 128 {
					return fmt.Errorf("%s: RPC method path exceeds 128 bytes", method.Desc.FullName())
				}
			}
		}
	}
	for _, file := range plugin.Files {
		if !file.Generate || len(file.Services) == 0 {
			continue
		}
		g := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+"_kanarpc.pb.go", file.GoImportPath)
		g.P("// Code generated by protoc-gen-kanarpc. DO NOT EDIT.")
		g.P("// source: ", file.Desc.Path())
		g.P("// KanaRPC generated SDK API: 1")
		g.P()
		g.P("package ", file.GoPackageName)
		g.P()
		g.P("const _ = ", rpc("SupportPackageIsVersion1"))
		g.P()
		for _, service := range file.Services {
			generateService(g, service)
		}
	}
	return nil
}

func methodPath(s *protogen.Service, m *protogen.Method) string {
	return "/" + string(s.Desc.FullName()) + "/" + string(m.Desc.Name())
}

func generateService(g *protogen.GeneratedFile, service *protogen.Service) {
	name := service.GoName
	private := strings.ToLower(name[:1]) + name[1:] + "Client"
	for _, m := range service.Methods {
		g.P("const ", name, "_", m.GoName, "_FullMethodName = ", fmt.Sprintf("%q", methodPath(service, m)))
	}
	g.P()
	g.P("type ", name, "Client interface {")
	for _, m := range service.Methods {
		if m.Desc.IsStreamingServer() {
			g.P(m.GoName, "(", contextType, ", *", m.Input.GoIdent, ") (", name, "_", m.GoName, "Client, error)")
		} else {
			g.P(m.GoName, "(", contextType, ", *", m.Input.GoIdent, ") (*", m.Output.GoIdent, ", error)")
		}
	}
	g.P("}")
	g.P("type ", private, " struct { caller ", rpc("ServiceCaller"), " }")
	g.P("func New", name, "Client(caller ", rpc("ServiceCaller"), ") ", name, "Client { return &", private, "{caller:caller} }")
	for _, m := range service.Methods {
		path := name + "_" + m.GoName + "_FullMethodName"
		if m.Desc.IsStreamingServer() {
			stream := name + "_" + m.GoName + "Client"
			wrapper := private + m.GoName + "Stream"
			g.P("type ", stream, " interface { Recv() (*", m.Output.GoIdent, ",error); Close() error }")
			g.P("type ", wrapper, " struct { stream ", rpc("Receiver"), " }")
			g.P("func (s *", wrapper, ") Recv() (*", m.Output.GoIdent, ",error) {")
			g.P("response := new(", m.Output.GoIdent, ")")
			g.P("if err := s.stream.Recv(response); err != nil { return nil,err }; return response,nil }")
			g.P("func (s *", wrapper, ") Close() error { return s.stream.Close() }")
			g.P("func (c *", private, ") ", m.GoName, "(ctx ", contextType, ", request *", m.Input.GoIdent, ") (", stream, ",error) {")
			g.P("stream,err := c.caller.OpenStream(ctx,", path, ",", rpc("Protobuf"), "(request))")
			g.P("if err != nil { return nil,err }; return &", wrapper, "{stream:stream},nil }")
		} else {
			g.P("func (c *", private, ") ", m.GoName, "(ctx ", contextType, ", request *", m.Input.GoIdent, ") (*", m.Output.GoIdent, ",error) {")
			g.P("response := new(", m.Output.GoIdent, ")")
			g.P("if err := c.caller.Call(ctx,", path, ",", rpc("Protobuf"), "(request),response); err != nil { return nil,err }; return response,nil }")
		}
	}
	g.P("type ", name, "Server interface {")
	g.P("mustEmbedUnimplemented", name, "Server()")
	for _, m := range service.Methods {
		if m.Desc.IsStreamingServer() {
			g.P(m.GoName, "(", contextType, ", *", m.Input.GoIdent, ",func(*", m.Output.GoIdent, ") error) error")
		} else {
			g.P(m.GoName, "(", contextType, ", *", m.Input.GoIdent, ") (*", m.Output.GoIdent, ",error)")
		}
	}
	g.P("}")
	g.P("// Unimplemented", name, "Server provides forward-compatible method defaults. Embed it by value.")
	g.P("type Unimplemented", name, "Server struct{}")
	g.P("func (Unimplemented", name, "Server) mustEmbedUnimplemented", name, "Server() {}")
	for _, m := range service.Methods {
		if m.Desc.IsStreamingServer() {
			g.P("func (Unimplemented", name, "Server) ", m.GoName, "(", contextType, ", *", m.Input.GoIdent, ",func(*", m.Output.GoIdent, ")error)error {")
			g.P("return &", rpc("Status"), "{Code:", rpc("NotFound"), ",Message:\"method not implemented\"} }")
		} else {
			g.P("func (Unimplemented", name, "Server) ", m.GoName, "(", contextType, ", *", m.Input.GoIdent, ")(*", m.Output.GoIdent, ",error) {")
			g.P("return nil,&", rpc("Status"), "{Code:", rpc("NotFound"), ",Message:\"method not implemented\"} }")
		}
	}
	g.P("func Register", name, "Server(server *", rpc("Server"), ", implementation ", name, "Server) error {")
	g.P("if implementation == nil { return ", protogen.GoImportPath("errors").Ident("New"), "(\"kanarpc: nil service implementation\") }")
	g.P("return ", rpc("RegisterProtobufMethods"), "(server,")
	for _, m := range service.Methods {
		g.P(rpc("ProtobufMethod"), "{ Path:", name, "_", m.GoName, "_FullMethodName,")
		g.P("NewRequest: func() ", protoType, " { return new(", m.Input.GoIdent, ") },")
		if m.Desc.IsStreamingServer() {
			g.P("Stream: func(ctx ", contextType, ", request ", protoType, ", send func(", protoType, ") error) error {")
			g.P("return implementation.", m.GoName, "(ctx,request.(*", m.Input.GoIdent, "),func(response *", m.Output.GoIdent, ") error { return send(response) }) },")
		} else {
			g.P("Unary: func(ctx ", contextType, ", request ", protoType, ") (", protoType, ",error) {")
			g.P("return implementation.", m.GoName, "(ctx,request.(*", m.Input.GoIdent, ")) },")
		}
		g.P("},")
	}
	g.P(") }")
	g.P()
}
